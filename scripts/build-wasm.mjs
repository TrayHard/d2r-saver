// Builds the Rust read core as WebAssembly and embeds it as `src/engine/wasm-module.ts`.
// Needs cargo and the wasm32-unknown-unknown target (`rustup target add wasm32-unknown-unknown`).
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const cargo = spawnSync(
  'cargo',
  ['build', '--release', '-p', 'd2r-saver-wasm', '--target', 'wasm32-unknown-unknown'],
  { cwd: `${root}rust`, stdio: 'inherit', windowsHide: true },
);
if (cargo.status !== 0) {
  console.error(cargo.error?.message ?? `cargo exited with ${cargo.status}`);
  process.exit(1);
}
const wasm = readFileSync(`${root}rust/target/wasm32-unknown-unknown/release/d2r_saver_wasm.wasm`);
writeFileSync(
  `${root}src/engine/wasm-module.ts`,
  `// Generated by scripts/build-wasm.mjs from rust/wasm (${wasm.length} bytes); do not edit.\n`
    + `export default '${wasm.toString('base64')}';\n`,
);
console.log(`src/engine/wasm-module.ts: ${wasm.length} bytes of WebAssembly`);
